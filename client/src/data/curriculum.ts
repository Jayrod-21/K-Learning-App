/**
 * Get all units as a flat array
 */
export function getAllUnits(): Unit[] {
  return curriculum.flatMap((phase) => phase.units);
}

/**
 * Get a specific unit by ID
 */
export function getUnitById(unitId: string): Unit | undefined {
  return getAllUnits().find((u) => u.id === unitId);
}

/**
 * Get a specific lesson by ID
 */
export function getLessonById(lessonId: string): { unit: Unit; lesson: Lesson } | undefined {
  for (const unit of getAllUnits()) {
    const lesson = unit.lessons.find((l) => l.id === lessonId);
    if (lesson) return { unit, lesson };
  }
  return undefined;
}
